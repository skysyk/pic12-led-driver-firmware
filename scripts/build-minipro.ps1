param(
    [string]$Zig = '',
    [string]$Zlib = ''
)
$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
if (!$Zig) { $Zig = Join-Path $projectRoot '.tools/zig-x86_64-windows-0.15.2/zig.exe' }
if (!$Zlib) { $Zlib = Join-Path $projectRoot '.tools/zlib-1.3.2' }
$source = Join-Path $projectRoot 'minipro'
$output = Join-Path $projectRoot 'build/minipro'
foreach ($required in @($Zig, "$Zlib/zlib.h", "$source/src/usb_win.c")) {
    if (!(Test-Path -LiteralPath $required)) { throw "Missing build prerequisite: $required" }
}
New-Item -ItemType Directory -Force -Path $output | Out-Null
$env:ZIG_GLOBAL_CACHE_DIR = Join-Path $projectRoot 'build/zig-global-cache'
$env:ZIG_LOCAL_CACHE_DIR = Join-Path $projectRoot 'build/zig-local-cache'
Push-Location $source
try {
    $hash = git rev-parse HEAD
    if ($LASTEXITCODE) { throw 'Cannot determine minipro revision.' }
    $branch = git rev-parse --abbrev-ref HEAD
    $date = git show -s --format=%ci
    $versionLine = Get-Content Makefile | Where-Object { $_ -match '^VERSION\s*=' } | Select-Object -First 1
    $version = ($versionLine -split '=', 2)[1].Trim()
    $share = $output.Replace('\', '/')
    @"
/* Generated by scripts/build-minipro.ps1. */
#define VERSION "$version"
#define GIT_BRANCH "$branch"
#define GIT_HASH "$hash"
#define GIT_DATE "$date"
#define SHARE_INSTDIR "$share"
"@ | Set-Content -LiteralPath "$output/version.h" -Encoding ascii

    # Same source list as upstream Makefile, using the native Windows USB backend.
    # version.c only includes headers; version.h above supplies its metadata.
    $miniproSources = @('xml', 'jedec', 'ihex', 'srec', 'database', 'bitbang',
        'prom', 'minipro', 'tl866a', 'tl866iiplus', 't48', 't56', 't76',
        'cdecode', 'cencode', 'usb_win', 'main') | ForEach-Object { "src/$_.c" }
    $zlibSources = @('adler32', 'compress', 'crc32', 'deflate', 'gzclose',
        'gzlib', 'gzread', 'gzwrite', 'infback', 'inffast', 'inflate',
        'inftrees', 'trees', 'uncompr', 'zutil') | ForEach-Object { "$Zlib/$_.c" }
    $options = @('-target', 'x86_64-windows-gnu', '-std=gnu11', '-O2',
        '-Wall', '-Wextra', '-Wno-sign-compare', '-Wno-unused-parameter',
        "-I$output", "-I$Zlib", '-include', "$PSScriptRoot/minipro-windows-compat.h")
    & $Zig cc @options @miniproSources @zlibSources -lsetupapi -lwinusb -lshlwapi -lshell32 -o "$output/minipro.exe"
    if ($LASTEXITCODE) { throw 'Minipro compilation failed.' }
    Copy-Item -LiteralPath infoic.xml, logicic.xml, LICENSE -Destination $output
    Copy-Item -LiteralPath "$Zlib/LICENSE" -Destination "$output/LICENSE-zlib"
    Write-Output "Built $output/minipro.exe from $hash"
} finally { Pop-Location }
